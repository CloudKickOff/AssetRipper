using AsmResolver.DotNet;
using AssetRipper.Export.Scripts;
using AssetRipper.Import.Configuration;
using AssetRipper.Import.Logging;
using AssetRipper.Import.Structure.Assembly;
using AssetRipper.Import.Structure.Assembly.Managers;
using ICSharpCode.Decompiler;
using ICSharpCode.Decompiler.CSharp;
using ICSharpCode.Decompiler.CSharp.ProjectDecompiler;

namespace AssetRipper.Export.UnityProjects.Scripts;

internal class ScriptDecompiler
{
	private readonly ILSpyAssemblyResolver assemblyResolver;
	public LanguageVersion LanguageVersion { get; set; } = LanguageVersion.CSharp7_3;
	public ScriptContentLevel ScriptContentLevel { get; set; } = ScriptContentLevel.Level2;
	public ScriptingBackend ScriptingBackend { get; set; } = ScriptingBackend.Unknown;
	public bool FullyQualifiedTypeNames { get; set; } = false;

	public ScriptDecompiler(IAssemblyManager assemblyManager) : this(new ILSpyAssemblyResolver(assemblyManager), assemblyManager.ScriptingBackend) { }
	private ScriptDecompiler(ILSpyAssemblyResolver assemblyResolver, ScriptingBackend scriptingBackend)
	{
		this.assemblyResolver = assemblyResolver;
		ScriptingBackend = scriptingBackend;
	}

	public void DecompileWholeProject(AssemblyDefinition assembly, string outputFolder, FileSystem fileSystem)
	{
		DecompilerSettings settings = CreateSettings();

		CustomWholeProjectDecompiler decompiler = new(settings, assemblyResolver, fileSystem);

		DecompileWholeProject(decompiler, assembly, outputFolder);
	}

	/// <summary>
	/// Decompile only some top level types of an assembly (with their nested types), laid out as in a whole project.
	/// </summary>
	/// <param name="includeType">Whether to include a top level type, by full name.</param>
	public void DecompileTypes(AssemblyDefinition assembly, string outputFolder, FileSystem fileSystem, Func<string, bool> includeType)
	{
		DecompilerSettings settings = CreateSettings();
		CustomWholeProjectDecompiler decompiler = new(settings, assemblyResolver, fileSystem) { IncludeType = includeType, OutputFolder = outputFolder };
		DecompileWholeProject(decompiler, assembly, outputFolder);
	}

	private DecompilerSettings CreateSettings()
	{
		DecompilerSettings settings = new();

		settings.SetLanguageVersion(LanguageVersion);

		settings.AlwaysShowEnumMemberValues = true;
		settings.ShowXmlDocumentation = true;

		settings.UseNestedDirectoriesForNamespaces = true;

		if (FullyQualifiedTypeNames)
		{
			settings.AlwaysUseGlobal = true;
			settings.UsingDeclarations = false;
		}
		return settings;
	}

	private void DecompileWholeProject(WholeProjectDecompiler decompiler, AssemblyDefinition assembly, string outputFolder)
	{
		try
		{
			decompiler.DecompileProject(assemblyResolver.Resolve(assembly), outputFolder, TextWriter.Null);
		}
		catch (Exception exception)
		{
			Logger.Error(exception);
		}
	}

	private sealed class CustomWholeProjectDecompiler(DecompilerSettings settings, ILSpyAssemblyResolver assemblyResolver, FileSystem fileSystem) : ILSpyWholeProjectDecompiler(settings, assemblyResolver, NullProjectFileWriter.Instance, fileSystem)
	{
		/// <summary>
		/// Which top level types to decompile, by full name; all of them if null.
		/// </summary>
		public Func<string, bool>? IncludeType { get; init; }

		/// <summary>
		/// The folder the project is decompiled to, needed with <see cref="IncludeType"/>.
		/// </summary>
		public string OutputFolder { get; init; } = "";

		protected override bool IncludeTypeWhenDecompilingProject(ICSharpCode.Decompiler.Metadata.MetadataFile module, System.Reflection.Metadata.TypeDefinitionHandle type)
		{
			if (!base.IncludeTypeWhenDecompilingProject(module, type))
			{
				return false;
			}
			if (IncludeType is null)
			{
				return true;
			}
			System.Reflection.Metadata.TypeDefinition definition = module.Metadata.GetTypeDefinition(type);
			string name = module.Metadata.GetString(definition.Name);
			string @namespace = module.Metadata.GetString(definition.Namespace);
			return IncludeType(@namespace.Length == 0 ? name : $"{@namespace}.{name}");
		}

		protected override TextWriter CreateFile(string path)
		{
			string fileName = FileSystem.Path.GetFileName(path);
			if (fileName is "UnitySourceGeneratedAssemblyMonoScriptTypes_v1.cs")
			{
				// UnitySourceGeneratedAssemblyMonoScriptTypes_v1 is generated by Unity and should not be decompiled
				return TextWriter.Null;
			}
			if (fileName.StartsWith("__JobReflectionRegistrationOutput__", StringComparison.Ordinal))
			{
				// This is generated by Unity's job system when compiling, and it uses an internal attribute, so it can't be compiled from source.
				return TextWriter.Null;
			}
			if (IncludeType is not null && !IncludeFile(path))
			{
				return TextWriter.Null;
			}

			return base.CreateFile(path);
		}

		/// <summary>
		/// Whether a file is one of the included types'. The decompiler also writes the types that included ones depend
		/// on, such as their base types, and the assembly attributes, which the other assembly has its own of.
		/// </summary>
		private bool IncludeFile(string path)
		{
			string relativePath = FileSystem.Path.GetRelativePath(OutputFolder, path);
			if (!relativePath.EndsWith(".cs", StringComparison.Ordinal))
			{
				return true;
			}
			// Files are named after their type, in a folder for each part of its namespace.
			string typeName = relativePath[..^".cs".Length].Replace('\\', '.').Replace('/', '.');
			return IncludeType!(typeName) || IncludeTypeWithArity(typeName);
		}

		private bool IncludeTypeWithArity(string typeName)
		{
			// A generic type's file has no arity in its name.
			for (int arity = 1; arity <= 4; arity++)
			{
				if (IncludeType!($"{typeName}`{arity}"))
				{
					return true;
				}
			}
			return false;
		}
	}
}
